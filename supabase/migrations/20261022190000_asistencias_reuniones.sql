-- Registro de asistencia de afiliados/coordinadores a reuniones del calendario.
-- Solo se guarda una fila cuando la persona asistió (presente = existe fila,
-- ausente = no existe fila), para que marcar/desmarcar en tablet sea un simple
-- insert/delete.
create table public.asistencias (
  id bigint generated by default as identity primary key,
  reunion_id bigint not null references public.reuniones(id) on delete cascade,
  afiliado_id bigint not null references public.afiliados(id) on delete cascade,
  registrado_por uuid references public.perfiles(id) on delete set null,
  registrado_en timestamptz not null default now(),
  unique (reunion_id, afiliado_id)
);

create index idx_asistencias_reunion on public.asistencias (reunion_id);
create index idx_asistencias_afiliado on public.asistencias (afiliado_id);

alter table public.asistencias enable row level security;

create policy "admin_pentagono_select_asistencias"
on public.asistencias for select
to authenticated
using (exists (select 1 from perfiles p where p.id = auth.uid() and p.rol in ('admin','pentagono')));

create policy "admin_pentagono_insert_asistencias"
on public.asistencias for insert
to authenticated
with check (exists (select 1 from perfiles p where p.id = auth.uid() and p.rol in ('admin','pentagono')));

create policy "admin_pentagono_delete_asistencias"
on public.asistencias for delete
to authenticated
using (exists (select 1 from perfiles p where p.id = auth.uid() and p.rol in ('admin','pentagono')));

-- Las tablas creadas después de que el proyecto dejó de auto-exponer tablas
-- nuevas (ver supabase/config.toml) necesitan GRANT explícito además de RLS,
-- o el cliente autenticado recibe "permission denied" aunque la policy pase.
grant select, insert, delete on public.asistencias to authenticated;
